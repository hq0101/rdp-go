// Package licensing implements the bounded MS-RDPELE client exchange over an
// already authenticated RDP transport. Certificate verification requires an
// independent trust decision; no trust follows from a signature alone. It does
// not open connections, inspect hardware, or persist CALs. Session integration
// is responsible for transport trust, identity, storage and protocol I/O.
package licensing

import (
	"bytes"
	"encoding/binary"
	"errors"
	"fmt"
	"io"
	"unicode/utf16"
)

const (
	RequestMessage     byte = 1
	ChallengeMessage   byte = 2
	NewLicenseMessage  byte = 3
	UpgradeMessage     byte = 4
	LicenseInfoMessage byte = 0x12
	NewRequestMessage  byte = 0x13
	ResponseMessage    byte = 0x15
	ErrorMessage       byte = 0xff
	MaxPacket               = 65539 // Four-byte basic security header plus uint16 licensing size.
	MaxText                 = 4096
	MaxScopes               = 64
	MaxLicense              = 60000
	MaxChallenge            = 4096
)

var (
	ErrInvalid       = errors.New("licensing: invalid message")
	ErrState         = errors.New("licensing: unexpected message or operation")
	ErrMAC           = errors.New("licensing: integrity verification failed")
	ErrKey           = errors.New("licensing: invalid RSA public key")
	ErrCrypto        = errors.New("licensing: required legacy cryptography is unavailable")
	ErrLimit         = errors.New("licensing: exchange limit exceeded")
	ErrClosed        = errors.New("licensing: client closed")
	ErrCachedLicense = errors.New("licensing: cached license does not match product, issuer or client identity")
)

type ServerError struct{ Code, Transition uint32 }

func (e *ServerError) Error() string {
	return fmt.Sprintf("licensing: server error 0x%08x, transition %d", e.Code, e.Transition)
}

// redacted prevents accidental logging of credentials, hardware IDs and CALs,
// including through a containing Result. Explicit field access is internal-only.
type redacted struct{}

func (redacted) Format(s fmt.State, _ rune)   { io.WriteString(s, "licensing:<redacted>") }
func (redacted) MarshalJSON() ([]byte, error) { return []byte(`{"redacted":true}`), nil }

type Product struct {
	Version     uint32
	Company, ID string
}
type Request struct {
	redacted
	Product     Product
	Scopes      [][]byte // Exact ANSI bytes without the terminal NUL; not UTF-8 names.
	Certificate []byte   // Opaque SERVER_CERTIFICATE, not an authenticated public key.
	random      [32]byte
}

func (r *Request) clone() *Request {
	if r == nil {
		return nil
	}
	n := *r
	n.Certificate = bytes.Clone(r.Certificate)
	n.Scopes = make([][]byte, len(r.Scopes))
	for i, s := range r.Scopes {
		n.Scopes[i] = bytes.Clone(s)
	}
	return &n
}
func (r *Request) Clear() {
	if r == nil {
		return
	}
	clear(r.Certificate)
	for _, s := range r.Scopes {
		clear(s)
	}
	*r = Request{}
}

// License owns its Data and Scope. Clear after an application has safely stored
// its own copy. Data is an opaque, server-issued CAL, never generated by us.
type License struct {
	redacted
	Product     Product
	Scope, Data []byte
	HardwareID  [20]byte
}

func (l *License) Clear() {
	if l != nil {
		clear(l.Data)
		clear(l.Scope)
		*l = License{}
	}
}
func (l *License) Matches(r *Request, hwid [20]byte) bool {
	if l == nil || r == nil || l.Product != r.Product || l.HardwareID != hwid || len(l.Data) == 0 || len(l.Data) > MaxLicense {
		return false
	}
	for _, s := range r.Scopes {
		if bytes.Equal(s, l.Scope) {
			return true
		}
	}
	return false
}

type message struct {
	kind             byte
	request          *Request
	encrypted        []byte
	mac              [16]byte
	code, transition uint32
}

type reader struct {
	b   []byte
	bad bool
}

func (r *reader) take(n int) []byte {
	if n < 0 || n > len(r.b) {
		r.bad = true
		return nil
	}
	b := r.b[:n]
	r.b = r.b[n:]
	return b
}
func (r *reader) u16() uint16 {
	b := r.take(2)
	if b == nil {
		return 0
	}
	return binary.LittleEndian.Uint16(b)
}
func (r *reader) u32() uint32 {
	b := r.take(4)
	if b == nil {
		return 0
	}
	return binary.LittleEndian.Uint32(b)
}
func (r *reader) sized(max int) []byte {
	n := r.u32()
	if uint64(n) > uint64(max) {
		r.bad = true
		return nil
	}
	return r.take(int(n))
}
func (r *reader) blob(kind uint16, max int, anyType bool) []byte {
	t, n := r.u16(), int(r.u16())
	if (!anyType && t != kind) || n > max {
		r.bad = true
		return nil
	}
	return r.take(n)
}
func ansi(b []byte) bool {
	return len(b) > 0 && len(b) <= MaxText && b[len(b)-1] == 0 && bytes.IndexByte(b[:len(b)-1], 0) < 0
}
func unicodeString(b []byte) (string, bool) {
	if len(b) < 2 || len(b) > MaxText || len(b)%2 != 0 || binary.LittleEndian.Uint16(b[len(b)-2:]) != 0 {
		return "", false
	}
	u := make([]uint16, len(b)/2-1)
	for i := range u {
		u[i] = binary.LittleEndian.Uint16(b[i*2:])
		if u[i] == 0 {
			return "", false
		}
	}
	for i := 0; i < len(u); i++ {
		if u[i] >= 0xd800 && u[i] <= 0xdbff {
			i++
			if i == len(u) || u[i] < 0xdc00 || u[i] > 0xdfff {
				return "", false
			}
		} else if u[i] >= 0xdc00 && u[i] <= 0xdfff {
			return "", false
		}
	}
	return string(utf16.Decode(u)), true
}
func (r *reader) text() string {
	s, ok := unicodeString(r.sized(MaxText))
	if !ok {
		r.bad = true
	}
	return s
}

// parse accepts an entire licensing packet with a basic security header, not
// encrypted Standard Security packets. flagsHi is unused without its valid bit.
func parse(b []byte) (m message, err error) {
	if len(b) < 8 || len(b) > MaxPacket || binary.LittleEndian.Uint16(b) != 0x80 || b[5]&0x7f != 3 || int(binary.LittleEndian.Uint16(b[6:])) != len(b)-4 {
		return m, ErrInvalid
	}
	m.kind = b[4]
	r := reader{b: b[8:]}
	switch m.kind {
	case RequestMessage:
		q := &Request{}
		copy(q.random[:], r.take(32))
		q.Product.Version = r.u32()
		q.Product.Company = r.text()
		q.Product.ID = r.text()
		algorithms := r.blob(13, 64, false)
		rsaOK := false
		if len(algorithms) == 0 || len(algorithms)%4 != 0 {
			r.bad = true
		}
		for i := 0; i+4 <= len(algorithms); i += 4 {
			if binary.LittleEndian.Uint32(algorithms[i:]) == 1 {
				rsaOK = true
			}
		}
		if !rsaOK {
			r.bad = true
		}
		q.Certificate = bytes.Clone(r.blob(3, 65535, false))
		count := r.u32()
		if count > MaxScopes || uint64(count)*5 > uint64(len(r.b)) {
			r.bad = true
		} else {
			for i := uint32(0); i < count; i++ {
				s := r.blob(14, MaxText, false)
				if !ansi(s) {
					r.bad = true
					break
				}
				q.Scopes = append(q.Scopes, bytes.Clone(s[:len(s)-1]))
			}
		}
		m.request = q
	case ChallengeMessage:
		r.u32() // Reserved ConnectFlags; Microsoft's sample contains 0xffffffff.
		// This tag is explicitly unused, including in the official 0xf750 sample.
		m.encrypted = r.blob(0, MaxChallenge, true)
		if len(m.encrypted) == 0 {
			r.bad = true
		}
		copy(m.mac[:], r.take(16))
	case NewLicenseMessage, UpgradeMessage:
		// Pre-2008 servers leave this tag undefined. Integrity is checked before use.
		m.encrypted = r.blob(0, 65535, true)
		if len(m.encrypted) == 0 {
			r.bad = true
		}
		copy(m.mac[:], r.take(16))
	case ErrorMessage:
		m.code, m.transition = r.u32(), r.u32()
		detail := r.blob(4, 65535, false)
		if m.code == 7 && len(detail) != 0 {
			r.bad = true
		}
		if m.transition < 1 || m.transition > 4 {
			r.bad = true
		}
	default:
		r.bad = true
	}
	if r.bad || len(r.b) != 0 {
		if m.request != nil {
			m.request.Clear()
		}
		return message{}, ErrInvalid
	}
	return m, nil
}

func parseLicense(b []byte, hwid [20]byte) (*License, error) {
	r := reader{b: b}
	l := &License{HardwareID: hwid}
	l.Product.Version = r.u32()
	scope := r.sized(MaxText)
	if !ansi(scope) {
		r.bad = true
	} else {
		l.Scope = bytes.Clone(scope[:len(scope)-1])
	}
	l.Product.Company = r.text()
	l.Product.ID = r.text()
	data := r.sized(MaxLicense)
	if len(data) == 0 {
		r.bad = true
	}
	if r.bad || len(r.b) != 0 {
		l.Clear()
		return nil, ErrInvalid
	}
	l.Data = bytes.Clone(data)
	return l, nil
}

func blob(b []byte, kind uint16, data []byte) []byte {
	b = binary.LittleEndian.AppendUint16(b, kind)
	b = binary.LittleEndian.AppendUint16(b, uint16(len(data)))
	return append(b, data...)
}
func packet(kind byte, body []byte) ([]byte, error) {
	if len(body) > MaxPacket-8 {
		return nil, ErrLimit
	}
	b := []byte{0x80, 0, 0, 0, kind, 0x83, 0, 0}
	binary.LittleEndian.PutUint16(b[6:], uint16(len(body)+4))
	return append(b, body...), nil
}
func abortPacket(code uint32) []byte {
	b := binary.LittleEndian.AppendUint32(nil, code)
	b = binary.LittleEndian.AppendUint32(b, 1)
	b = blob(b, 4, nil)
	out, _ := packet(ErrorMessage, b)
	return out
}
